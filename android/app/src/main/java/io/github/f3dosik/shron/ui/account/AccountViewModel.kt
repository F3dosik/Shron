package io.github.f3dosik.shron.ui.account

import androidx.compose.runtime.getValue
import androidx.compose.runtime.mutableStateOf
import androidx.compose.runtime.setValue
import io.github.f3dosik.shron.R
import io.github.f3dosik.shron.ShronApplication
import io.github.f3dosik.shron.core.GeneratedPassword
import io.github.f3dosik.shron.core.GeneratorSettings
import io.github.f3dosik.shron.ui.common.CoreViewModel
import java.security.GeneralSecurityException
import javax.crypto.Cipher

/** Учётка: смена мастер-пароля, выход на всех устройствах, удаление учётки. */
class AccountViewModel(app: ShronApplication) : CoreViewModel(app) {

    var currentPassword by mutableStateOf("")
    var newPassword by mutableStateOf("")
        private set
    var confirm by mutableStateOf("")
        private set
    var generated by mutableStateOf<GeneratedPassword?>(null)
        private set
    var generator by mutableStateOf(GeneratorSettings(passphrase = true))
        private set

    /** Параметры Argon2id для нового пароля; по умолчанию как domain.DefaultKDFParams. */
    var kdfTime by mutableStateOf(DEFAULT_KDF_TIME.toString())
    var kdfMemoryMiB by mutableStateOf(DEFAULT_KDF_MEMORY_MIB.toString())

    var deleteLogin by mutableStateOf("")
    var deletePassword by mutableStateOf("")

    var notice by mutableStateOf<String?>(null)
        private set

    /** Разблокировка по биометрии включена для этой учётки. */
    var biometricEnabled by mutableStateOf(false)
        private set
    val biometricAvailable: Boolean get() = app.biometric.isAvailable()

    init {
        refreshBiometric()
    }

    private fun refreshBiometric() {
        val state = core.state.value
        biometricEnabled = app.biometric.isEnabled(state.serverAddress, state.biometricAccount)
    }

    // Ошибки биометрии — в Snackbar: поле ошибки на этом экране относится к смене пароля.

    /** Шифр нового ключа Keystore — его подтверждают биометрией, прежде чем сохранить ключ. */
    fun biometricEnrollCipher(): Cipher? = try {
        app.biometric.encryptCipher()
    } catch (_: GeneralSecurityException) {
        notice = string(R.string.biometric_unavailable)
        null
    }

    /** Сохраняет мастер-ключ под защитой биометрии; [cipher] уже подтверждён. */
    fun enableBiometric(cipher: Cipher) = run {
        val state = core.state.value
        val key = core.call { it.masterKey() }
        notice = try {
            app.biometric.save(cipher, key, state.serverAddress, state.biometricAccount)
            string(R.string.biometric_enabled)
        } catch (_: GeneralSecurityException) {
            app.biometric.clear()
            string(R.string.biometric_failed)
        } finally {
            key.fill(0)
        }
        refreshBiometric()
    }

    fun disableBiometric() {
        app.biometric.clear()
        refreshBiometric()
    }

    fun biometricError(message: String) {
        notice = message
    }

    fun updateNewPassword(value: String) {
        newPassword = value
        generated = null
    }

    fun updateConfirm(value: String) {
        confirm = value
        generated = null
    }

    fun updateGenerator(settings: GeneratorSettings, regenerate: Boolean) {
        generator = settings
        if (regenerate) generatePassword()
    }

    fun generatePassword() = run {
        val result = core.generate(generator)
        newPassword = result.password
        confirm = result.password
        generated = result
    }

    /** Перешифровывает все секреты; ядро затем разблокирует хранилище новым паролем. */
    fun changePassword() = run {
        if (newPassword != confirm) throw validation(R.string.passwords_mismatch)
        val time = kdfTime.toLongOrNull() ?: throw validation(R.string.kdf_invalid)
        val memory = kdfMemoryMiB.toLongOrNull() ?: throw validation(R.string.kdf_invalid)
        core.call { it.changePassword(currentPassword, newPassword, time, memory) }
        currentPassword = ""
        newPassword = ""
        confirm = ""
        generated = null
        // Сохранённый ключ выведен из прежнего пароля и сервером больше не принимается.
        if (biometricEnabled) {
            disableBiometric()
            notice = string(R.string.password_changed_biometric_off)
        } else {
            notice = string(R.string.password_changed)
        }
    }

    fun noticeShown() {
        notice = null
    }

    fun logoutEverywhere() = run {
        core.call { it.logout(true) }
        app.biometric.clear()
    }

    /** Удаляет учётку навсегда; [login] введён повторно для подтверждения. */
    fun deleteAccount(login: String?) = run {
        // У хранилища без сервера логина нет ([login] == null): хватает пароля.
        if (login != null && deleteLogin.trim() != login) throw validation(R.string.delete_account_login_mismatch)
        core.call { it.deleteAccount(deletePassword) }
        app.biometric.clear()
    }

    fun resetDeleteForm() {
        deleteLogin = ""
        deletePassword = ""
        dismissError()
    }

    private companion object {
        const val DEFAULT_KDF_TIME = 3
        const val DEFAULT_KDF_MEMORY_MIB = 64
    }
}
